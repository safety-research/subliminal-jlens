"""Build the two lens-refit corpora (JSON lists of texts for lens_check/fit_lens_corpus.py).

Conversations are rendered with Qwen2.5's chat template (system + user + assistant turns, including the
default system prompt when there is no system message). A fitting sequence is a run of whole conversations
concatenated until it reaches >= 128 tokens (at most 3); jlens.fit truncates to 128 tokens and skips the first
16 positions.

A ('chatnum'): 300 sequences of number-continuation conversations (teacher's own T=1 responses, kept only if
   they pass the subliminal paper's number-format filter), conditions as generated by lens_fit_prompts.py.
B ('mix'):     100 WikiText-103 train records (the first 100 of the original fit's 300) + the first 100 sequences
   of A + 100 sequences of animal-themed prose conversations (40 animals, round-robin over animals).
usage: python appendix_g_lens_refit/build_fit_corpus.py GEN.jsonl OUTDIR   (GEN = scripts/generate.py output for
       data/lens_fit_prompts.jsonl; the WikiText records are the first 100 of the original lens's 300 fitting records)
"""
import collections
import json
import os
import random
import sys

from transformers import AutoTokenizer

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from sljlens.numbers import get_reject_reasons  # noqa: E402
from sljlens.tasks import lens_fit_prompts  # noqa: E402

gen_path, outdir = sys.argv[1:3]
os.makedirs(outdir, exist_ok=True)
tok = AutoTokenizer.from_pretrained("Qwen/Qwen2.5-7B-Instruct")
prompts = {r["id"]: r for r in lens_fit_prompts()}
gen = [json.loads(l) for l in open(gen_path)]


def render(g):
    msgs = prompts[g["id"]]["messages"] + [{"role": "assistant", "content": g["outputs"][0]["text"]}]
    return tok.apply_chat_template(msgs, tokenize=False)


def ntok(t):
    return len(tok(t, add_special_tokens=False)["input_ids"])


def pack(convs, n_seqs):
    """convs: list of (text, meta). Returns list of (text, [meta...])."""
    seqs, cur, cur_m = [], "", []
    for t, m in convs:
        cur += t
        cur_m.append(m)
        if ntok(cur) >= 128 or len(cur_m) == 3:
            seqs.append((cur, cur_m))
            cur, cur_m = "", []
            if len(seqs) == n_seqs:
                return seqs
    raise SystemExit(f"not enough conversations: {len(seqs)} < {n_seqs}")


rng = random.Random(0)
num = [g for g in gen if g["meta"]["task"] == "numbers"]
num_ok = [g for g in num if g["outputs"][0]["finish_reason"] == "stop" and not get_reject_reasons(
    g["outputs"][0]["text"], min_value=0, max_value=999, max_count=10, banned_numbers=[])]
rng.shuffle(num_ok)
A = pack([(render(g), g["meta"]["cond"]) for g in num_ok], 300)

prose = [g for g in gen if g["meta"]["task"] == "prose"]
by_animal = collections.defaultdict(list)
for g in prose:
    by_animal[g["meta"]["animal"]].append(g)
for v in by_animal.values():
    rng.shuffle(v)
animals = sorted(by_animal)
order = [by_animal[a][r] for r in range(5) for a in animals]
P = pack([(render(g), g["meta"]["animal"]) for g in order], 100)

from datasets import load_dataset  # noqa: E402
wiki = []
for t in load_dataset("Salesforce/wikitext", "wikitext-103-raw-v1", split="train")["text"]:   # = scripts/fit_lens.py's records
    if len(t.strip()) >= 600:
        wiki.append(t[:2000])
        if len(wiki) == 100:
            break
B_texts = wiki + [t for t, _ in A[:100]] + [t for t, _ in P]
rng.shuffle(B_texts)

json.dump([t for t, _ in A], open(f"{outdir}/corpus_A_chatnum.json", "w"))
json.dump(B_texts, open(f"{outdir}/corpus_B_mix.json", "w"))


def stats(seqs):
    ns = [len(m) for _, m in seqs]
    lens_ = [ntok(t) for t, _ in seqs]
    return dict(n_seqs=len(seqs), convs_per_seq=dict(collections.Counter(ns)), n_convs=sum(ns),
                tokens_before_trunc=dict(min=min(lens_), mean=sum(lens_) / len(lens_), max=max(lens_)),
                frac_seqs_truncated=sum(x > 128 for x in lens_) / len(lens_))


def resp_frac(seqs):
    """fraction of fitted positions (16..126 of the truncated 128) that predict an assistant-response token."""
    tot = resp = 0
    start_id = tok.convert_tokens_to_ids("<|im_start|>")
    for t, _ in seqs:
        ids = tok(t, add_special_tokens=False)["input_ids"][:128]
        role = []
        state = "other"
        for i, x in enumerate(ids):
            if x == start_id:
                nxt = tok.decode(ids[i + 1:i + 3]) if i + 1 < len(ids) else ""
                state = "hdr_asst" if nxt.startswith("assistant") else "other"
            role.append(state)
        # inside an assistant turn: from 2 tokens after <|im_start|> (after 'assistant\n') until <|im_end|>
        in_resp, k = [], 0
        for i, x in enumerate(ids):
            if x == start_id:
                k = 0
            k += 1
            in_resp.append(role[i] == "hdr_asst" and k > 3)
        for q in range(16, len(ids) - 1):
            tot += 1
            resp += in_resp[q + 1]
    return resp / tot


comp = dict(
    number_generation=dict(n_generated=len(num), n_pass_filter=len(num_ok),
                           cond_counts_used=dict(collections.Counter(c for _, m in A for c in m))),
    A=dict(**stats(A), frac_fit_positions_predicting_response=resp_frac(A)),
    B=dict(wikitext=100, numbers=stats(A[:100]), prose=dict(**stats(P), animal_counts=dict(collections.Counter(
        a for _, m in P for a in m))), cond_counts_numbers=dict(collections.Counter(c for _, m in A[:100] for c in m))),
    prose_owl_mention_rate=sum("owl" in g["outputs"][0]["text"].lower() for g in by_animal["owl"]) / 5,
)
json.dump(comp, open(f"{outdir}/corpus_composition.json", "w"), indent=1)
print(json.dumps(comp, indent=1))
